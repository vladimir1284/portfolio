#!/usr/bin/env python3
"""Generate dist/_headers for Cloudflare Pages.

The Content-Security-Policy is the reason this is generated rather than kept as
a static public/_headers: Layout.astro ships an inline theme script that must
run before paint, and Astro inlines the small behaviour bundle too. Allowing
them with 'unsafe-inline' would defeat the policy, so each inline <script> and
<style> in the built output is hashed and listed. A hash that drifts because a
script changed is regenerated on the next build; a policy written by hand would
silently keep blocking it.

Stdlib only. Runs as part of `pnpm build`.
"""

from __future__ import annotations

import base64
import hashlib
import re
import sys
from pathlib import Path

DIST = Path(__file__).resolve().parent.parent / "dist"

# Inline element with no src/href attribute. Astro emits attributes without
# quotes-free edge cases, so a non-greedy body match is enough here.
SCRIPT_RE = re.compile(r"<script(?![^>]*\bsrc=)([^>]*)>(.*?)</script>", re.S | re.I)
STYLE_RE = re.compile(r"<style([^>]*)>(.*?)</style>", re.S | re.I)

# The built pages fetch nothing third-party: fonts are self-hosted (see the
# note in Layout.astro), so every directive below is 'self' plus hashes.
#
# `offsite_hosts` is what keeps that honest. The policy is generated, so adding
# a Google Fonts link back would not fail the build — it would quietly ship a
# page whose stylesheet the CSP blocks, and nothing on the page would say so.
# Only elements CSP actually governs are checked. Anchors are left alone — the
# site links out on purpose — and so is a <link> that declares a relationship
# rather than fetching: `canonical` and `alternate` name this site's own
# absolute URLs and are never requested by the browser.
LINK_RE = re.compile(r"<link\b([^>]*)>", re.I)
ATTR_RE = re.compile(r"""\b([a-z-]+)\s*=\s*["']([^"']*)["']""", re.I)
SRC_RE = re.compile(r"""<(?:script|img|source)\b[^>]*\bsrc(?:set)?\s*=\s*["']([^"']+)""", re.I)
FETCHING_RELS = {"stylesheet", "preload", "modulepreload", "prefetch", "icon", "manifest"}
HOST_RE = re.compile(r"(?:https?:)?//([^/\s]+)")


def sha256_source(body: str) -> str:
    digest = hashlib.sha256(body.encode("utf-8")).digest()
    return f"'sha256-{base64.b64encode(digest).decode('ascii')}'"


def collect(pattern: re.Pattern[str], pages: list[Path]) -> list[str]:
    hashes: set[str] = set()
    for page in pages:
        for match in pattern.finditer(page.read_text(encoding="utf-8")):
            body = match.group(2)
            if body.strip():
                hashes.add(sha256_source(body))
    return sorted(hashes)


def offsite_hosts(pages: list[Path]) -> set[str]:
    """Hosts the built pages fetch from, other than their own origin."""
    hosts: set[str] = set()
    for page in pages:
        html = page.read_text(encoding="utf-8")

        urls = list(SRC_RE.findall(html))
        for attrs in LINK_RE.findall(html):
            attr = {k.lower(): v for k, v in ATTR_RE.findall(attrs)}
            rels = set(attr.get("rel", "").lower().split())
            if rels & FETCHING_RELS:
                urls.append(attr.get("href", ""))

        for url in urls:
            # A srcset is a comma-separated candidate list; a plain src splits
            # to one item, so the same path handles both.
            for candidate in url.split(","):
                match = HOST_RE.match(candidate.strip())
                if match:
                    hosts.add(match.group(1))
    return hosts


def main() -> int:
    if not DIST.is_dir():
        print("dist/ not found — run `astro build` first", file=sys.stderr)
        return 1

    pages = sorted(DIST.rglob("*.html"))
    if not pages:
        print("no HTML in dist/", file=sys.stderr)
        return 1

    script_hashes = collect(SCRIPT_RE, pages)
    style_hashes = collect(STYLE_RE, pages)

    if not script_hashes:
        print("no inline scripts found — did Layout.astro change?", file=sys.stderr)
        return 1

    offsite = offsite_hosts(pages)
    if offsite:
        print(
            "built pages fetch from " + ", ".join(sorted(offsite)) + " — the CSP "
            "below allows 'self' only, so these would be blocked at runtime. "
            "Either keep the asset local or add the host to the policy.",
            file=sys.stderr,
        )
        return 1

    csp = "; ".join(
        [
            "default-src 'self'",
            "script-src 'self' " + " ".join(script_hashes),
            " ".join(["style-src 'self'", *style_hashes]),
            "font-src 'self'",
            "img-src 'self' data:",
            "connect-src 'self'",
            "frame-ancestors 'none'",
            "base-uri 'self'",
            "form-action 'none'",
            "object-src 'none'",
            "upgrade-insecure-requests",
        ]
    )

    out = f"""# Generated by scripts/build_headers.py — do not edit by hand.
# Regenerated on every `pnpm build`; the CSP carries hashes of the inline
# scripts, so editing this file instead of the source silently breaks them.

/*
  Content-Security-Policy: {csp}
  Referrer-Policy: strict-origin-when-cross-origin
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Permissions-Policy: geolocation=(), camera=(), microphone=(), payment=(), interest-cohort=()
  Strict-Transport-Security: max-age=31536000; includeSubDomains

# Astro fingerprints these filenames, so they can never go stale.
/_astro/*
  Cache-Control: public, max-age=31536000, immutable

# Build artefacts regenerated from src/data — revalidate rather than cache hard.
/cv.pdf
  Cache-Control: public, max-age=3600
/cv.es.pdf
  Cache-Control: public, max-age=3600
"""

    (DIST / "_headers").write_text(out, encoding="utf-8")
    print(
        f"_headers: {len(script_hashes)} script hash(es), "
        f"{len(style_hashes)} style hash(es), {len(pages)} page(s)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
